
# Simple Calculator
# OSS GitHub Flow Practice


def add(a: int, b: int) -> int:
    return a + b


def subtract(a: int, b: int) -> int:
    return a - b


def main():
    print("Simple Calculator")
    print("Addition result:", add(10, 5))
    print("Subtraction result:", subtract(10, 5))


if __name__ == "__main__":
    main()
